    #[tokio::test]
    async fn remove_track_only_invalidates_selected_track_writes() {
        let temp = TempDir::new().unwrap();
        let cache = AudioCache::new(temp.path().into(), 256);
        let target = test_track("target-id", "Target");
        let other = test_track("other-id", "Other");
        let target_key = "soundcloud:target-id:standard:mp3:MP3_128";
        let other_key = "soundcloud:other-id:standard:mp3:MP3_128";
        let target_path = cache.block_path(target_key, 6, 0, 5);
        let other_path = cache.block_path(other_key, 5, 0, 4);
        let generation = cache.generation();
        let target_token = cache.track_token(target.provider, &target.id).await;
        let other_token = cache.track_token(other.provider, &other.id).await;

        cache
            .write_with_token(&target_path, b"target", generation, Some(&target_token))
            .await;
        cache
            .remember_track_with_token(&target, target_key, Some(6), Some(&target_token))
            .await;
        cache
            .remember_track_with_token(&other, other_key, Some(5), Some(&other_token))
            .await;

        assert!(
            cache
                .remove_track(PlaybackProvider::SoundCloud, &target.id)
                .await
                .unwrap()
        );
        assert!(cache.is_current(generation));
        assert!(!target_path.exists());

        // A stale writer cannot recreate the removed track's block.
        cache
            .write_with_token(&target_path, b"stale!", generation, Some(&target_token))
            .await;
        assert!(!target_path.exists());
        cache
            .remember_total_with_token(target_key, 6, generation, Some(&target_token))
            .await;
        assert!(!cache.total_path(target_key).exists());

        // A new operation for the removed track and an unrelated operation
        // remain valid under the unchanged global generation.
        let fresh_target_token = cache.track_token(target.provider, &target.id).await;
        cache
            .write_with_token(
                &target_path,
                b"fresh!",
                generation,
                Some(&fresh_target_token),
            )
            .await;
        cache
            .remember_track_with_token(&target, target_key, Some(6), Some(&target_token))
            .await;
        assert_eq!(tokio::fs::read(&target_path).await.unwrap(), b"fresh!");

        cache
            .write_with_token(&other_path, b"other", generation, Some(&other_token))
            .await;
        assert_eq!(tokio::fs::read(&other_path).await.unwrap(), b"other");
    }

