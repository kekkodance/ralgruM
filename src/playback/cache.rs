    #[tokio::test]
    async fn cached_variant_copy_is_cancellation_aware() {
        let temp = TempDir::new().unwrap();
        let cache = AudioCache::new(temp.path().into(), 256);
        let track = test_track("copy-id", "Copy");
        let key = "soundcloud:copy-id:standard:mp3:MP3";
        let total = 128 * 1024 + 17;
        let bytes = (0..total)
            .map(|value| (value % 251) as u8)
            .collect::<Vec<_>>();
        let path = cache.block_path(key, total, 0, total - 1);
        cache.write(&path, &bytes, cache.generation()).await;
        cache.remember_track(&track, key, Some(total)).await;
        let success_cancellation = CancellationToken::new();
        let cached = cache
            .complete_download_variant(&track, DownloadVariant::Standard, &success_cancellation)
            .await
            .expect("complete cache should be copyable");
        let success_path = temp.path().join("copy-success");
        let mut success_output = File::create(&success_path).await.unwrap();
        cache
            .copy_cached_variant(&cached, &mut success_output, &success_cancellation, None)
            .await
            .unwrap();
        drop(success_output);
        assert_eq!(tokio::fs::read(success_path).await.unwrap(), bytes);

        let cancellation = CancellationToken::new();
        let cached = cache
            .complete_download_variant(&track, DownloadVariant::Standard, &cancellation)
            .await
            .expect("complete cache should be copyable");
        let output_path = temp.path().join("copy.part");
        let mut output = File::create(&output_path).await.unwrap();
        let cancel_after_first_chunk = cancellation.clone();
        let progress = move |downloaded: u64, _: u64| {
            if downloaded >= 64 * 1024 {
                cancel_after_first_chunk.cancel();
            }
        };
        let error = cache
            .copy_cached_variant(&cached, &mut output, &cancellation, Some(&progress))
            .await
            .expect_err("cancellation must stop a cache copy");
        drop(output);
        assert_eq!(error, "Download request cancelled");
        let copied = tokio::fs::metadata(output_path).await.unwrap().len();
        assert!(copied >= 64 * 1024 && copied < total);

        tokio::fs::remove_file(&path).await.unwrap();
        let invalid_path = temp.path().join("copy-invalid.part");
        let mut invalid_output = File::create(&invalid_path).await.unwrap();
        let error = cache
            .copy_cached_variant(&cached, &mut invalid_output, &success_cancellation, None)
            .await
            .expect_err("an invalidated candidate must request network fallback");
        assert_eq!(error, CACHED_DOWNLOAD_INVALID);
    }

